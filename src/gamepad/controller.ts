/**
 * Game controllers, the pure part (no browser): which controller it is, the
 * names of its buttons, and turning raw button/stick readings into presses
 * with key-like repeat. `gamepad-input.ts` reads the browser and acts on them.
 */

export type ControllerFamily = 'xbox' | 'playstation' | 'nintendo' | 'generic'

/** Buttons by position (the browser's "standard" mapping follows the Xbox layout) */
export type PadButton =
  | 'a' | 'b' | 'x' | 'y'
  | 'lb' | 'rb' | 'lt' | 'rt'
  | 'select' | 'start' | 'l3' | 'r3'
  | 'up' | 'down' | 'left' | 'right'

export type Direction = 'up' | 'down' | 'left' | 'right'

/** Index of each button in `Gamepad.buttons` with the standard mapping */
export const STANDARD_BUTTONS: Record<PadButton, number> = {
  a: 0, b: 1, x: 2, y: 3,
  lb: 4, rb: 5, lt: 6, rt: 7,
  select: 8, start: 9, l3: 10, r3: 11,
  up: 12, down: 13, left: 14, right: 15
}

const DIRECTIONS: Direction[] = ['up', 'down', 'left', 'right']

/** Stick past this counts as a direction (menus and cursor) */
export const STICK_THRESHOLD = 0.5
/** Analog readings under this are noise (right stick, triggers) */
export const DEAD_ZONE = 0.2
/** Held direction: first repeat after this... */
export const REPEAT_DELAY_MS = 300
/** ...then one every */
export const REPEAT_EVERY_MS = 110

/**
 * Which controller, from `Gamepad.id`. Browsers name the same controller
 * differently (Chrome: "Xbox 360 Controller (XInput STANDARD GAMEPAD)",
 * Firefox: "045e-028e-...", Safari: "Xbox Wireless Controller"), so this
 * checks both names and USB vendor ids.
 */
export function controllerFamily(id: string): ControllerFamily {
  const name = id.toLowerCase()
  // Xbox first: Safari calls it "Xbox Wireless Controller", and a bare
  // "Wireless Controller" is the PlayStation's name
  if (/045e|xbox|xinput|microsoft/.test(name)) return 'xbox'
  if (/054c|dualshock|dualsense|playstation|wireless controller/.test(name)) return 'playstation'
  if (/057e|nintendo|pro controller|joy-con/.test(name)) return 'nintendo'
  return 'generic'
}

const FACE_LABELS: Record<ControllerFamily, Record<'a' | 'b' | 'x' | 'y', string>> = {
  xbox: { a: 'A', b: 'B', x: 'X', y: 'Y' },
  generic: { a: 'A', b: 'B', x: 'X', y: 'Y' },
  playstation: { a: '✕', b: '◯', x: '▢', y: '△' },
  // same positions, Nintendo letters: bottom is B, right is A
  nintendo: { a: 'B', b: 'A', x: 'Y', y: 'X' }
}

const OTHER_LABELS: Record<ControllerFamily, Record<Exclude<PadButton, 'a' | 'b' | 'x' | 'y'>, string>> = {
  xbox: { lb: 'LB', rb: 'RB', lt: 'LT', rt: 'RT', select: 'View', start: 'Menu', l3: 'LS', r3: 'RS', up: '↑', down: '↓', left: '←', right: '→' },
  generic: { lb: 'LB', rb: 'RB', lt: 'LT', rt: 'RT', select: 'Select', start: 'Start', l3: 'L3', r3: 'R3', up: '↑', down: '↓', left: '←', right: '→' },
  playstation: { lb: 'L1', rb: 'R1', lt: 'L2', rt: 'R2', select: 'Share', start: 'Options', l3: 'L3', r3: 'R3', up: '↑', down: '↓', left: '←', right: '→' },
  nintendo: { lb: 'L', rb: 'R', lt: 'ZL', rt: 'ZR', select: '−', start: '+', l3: 'LS', r3: 'RS', up: '↑', down: '↓', left: '←', right: '→' }
}

/** What is printed on `button` on this controller */
export function buttonLabel(family: ControllerFamily, button: PadButton): string {
  return button in FACE_LABELS[family]
    ? FACE_LABELS[family][button as 'a' | 'b' | 'x' | 'y']
    : OTHER_LABELS[family][button as keyof typeof OTHER_LABELS['xbox']]
}

/** One controller as read this frame */
export interface PadSnapshot {
  /** value of each button, 0..1, by standard index (triggers are analog) */
  buttons: number[]
  axes: number[]
}

export interface PadPress {
  button: PadButton
  /** generated by holding a direction, not a new press */
  repeat: boolean
}

/** Analog readings after the dead zone, every frame (camera) */
export interface PadAnalog {
  /** right stick, -1..1 */
  panX: number
  panY: number
  /** zoom out (LT) and in (RT), 0..1 */
  zoomOut: number
  zoomIn: number
}

/**
 * Turns snapshots into presses. Every connected controller counts (any one
 * can play). D-pad and left stick both give directions, and a held direction
 * repeats like a held key.
 */
export class PadTracker {
  private down = new Set<PadButton>()
  private repeatAt = new Map<Direction, number>()

  update(pads: PadSnapshot[], now: number): PadPress[] {
    const held = new Set<PadButton>()
    for (const pad of pads) {
      for (const [button, index] of Object.entries(STANDARD_BUTTONS) as [PadButton, number][]) {
        if ((pad.buttons[index] ?? 0) >= 0.5) held.add(button)
      }
      const [x = 0, y = 0] = pad.axes
      if (x <= -STICK_THRESHOLD) held.add('left')
      if (x >= STICK_THRESHOLD) held.add('right')
      if (y <= -STICK_THRESHOLD) held.add('up')
      if (y >= STICK_THRESHOLD) held.add('down')
    }

    const presses: PadPress[] = []
    for (const button of held) {
      if (this.down.has(button)) continue
      presses.push({ button, repeat: false })
      if ((DIRECTIONS as PadButton[]).includes(button)) this.repeatAt.set(button as Direction, now + REPEAT_DELAY_MS)
    }
    for (const direction of DIRECTIONS) {
      const at = this.repeatAt.get(direction)
      if (at === undefined) continue
      if (!held.has(direction)) {
        this.repeatAt.delete(direction)
      } else if (this.down.has(direction) && now >= at) {
        presses.push({ button: direction, repeat: true })
        this.repeatAt.set(direction, now + REPEAT_EVERY_MS)
      }
    }
    this.down = held
    return presses
  }

  /** Forget held buttons (a dialog closed under a held button must not see it again) */
  reset() {
    this.down.clear()
    this.repeatAt.clear()
  }
}

export function readAnalog(pads: PadSnapshot[]): PadAnalog {
  const analog: PadAnalog = { panX: 0, panY: 0, zoomOut: 0, zoomIn: 0 }
  for (const pad of pads) {
    const [, , rx = 0, ry = 0] = pad.axes
    if (Math.hypot(rx, ry) > DEAD_ZONE) {
      analog.panX += rx
      analog.panY += ry
    }
    const lt = pad.buttons[STANDARD_BUTTONS.lt] ?? 0
    const rt = pad.buttons[STANDARD_BUTTONS.rt] ?? 0
    if (lt > DEAD_ZONE) analog.zoomOut = Math.max(analog.zoomOut, lt)
    if (rt > DEAD_ZONE) analog.zoomIn = Math.max(analog.zoomIn, rt)
  }
  analog.panX = Math.max(-1, Math.min(1, analog.panX))
  analog.panY = Math.max(-1, Math.min(1, analog.panY))
  return analog
}
